GLOSSARY_MAX = 1500
TASK_MAX = 1500


def normalize_frequency(value) -> str:
    """«реже» / «обычно» / «чаще» (и английские ключи настроек); иное — по
    умолчанию «чаще»."""
    if isinstance(value, str):
        key = value.strip().lower()
        if key in FREQUENCIES:
            return key
        if key in _FREQUENCY_ALIASES:
            return _FREQUENCY_ALIASES[key]
    return DEFAULT_FREQUENCY


def frequency_phrase(value) -> str:
    """Фраза промпта для настройки «Как часто писать»."""
    return FREQUENCIES[normalize_frequency(value)]


def _section(title: str, body: str, limit: int | None = None) -> str:
    text = (body or "").strip()
    if not text:
        return ""
    if limit is not None and len(text) > limit:
        text = text[:limit].rstrip() + "…"
    return f"\n# {title}\n{text}\n"


def normalize_profile(value) -> str:
    """`work` / `personal` (и подписи «Рабочая встреча» / «Личный», прежнее
    `neutral`); иное — по умолчанию `work`."""
    if isinstance(value, str):
        key = value.strip().lower()
        if key in PROFILES:
            return key
        if key in PROFILE_ALIASES:
            return PROFILE_ALIASES[key]
        for name, label in PROFILES.items():
            if label.lower() == key:
                return name
    return DEFAULT_PROFILE


def profile_note(profile) -> str:
    """Пометка в ходе: пользователь сменил профиль по ходу сессии."""
    name = normalize_profile(profile)
    return f"Профиль сменён на «{PROFILES[name]}» — это заменяет прежние правила роли: {PROFILE_RULES[name]}"


def _owner_line(owner_name) -> str:
    owner = " ".join(str(owner_name or "").split())
    return (f" Пользователя зовут {safe_line(owner)}: обращение к нему по имени — вопрос "
            "к нему." if owner else "")


def _personal_system(*, frequency, tools_available: bool, owner_name: str,
                    folders: Mapping[str, str] | None, examples: bool,
                    freedom: bool = False, actions: bool = True, mode: str = "auto") -> str:
    """Промпт профиля «Личный»: без карты, рабочей рамки, контекста задачи и
    глоссария, без запросов к Meet; база знаний и прошлые записи — только по
    просьбе (0.4: доступ тот же, что у «Рабочей встречи», — отличие только в
    промпте). `freedom` (с инструментами) — тот же раздел «Возможности и
    согласие пользователя», что у «Рабочей встречи» (`_freedom_section`)."""
    name = normalize_frequency(frequency)
    free = bool(freedom and tools_available)
    tools = ""
    if tools_available:
        dirs = [f"\n  - {safe_line(label)}: {safe_line(path)}"
                for label, path in (folders or {}).items() if str(path or "").strip()]
        tools = _PERSONAL_TOOLS_ON.replace("@FOLDERS@", ("\n- Папки для чтения:" + "".join(dirs))
                                          if dirs else "")
    text = (_PERSONAL_ROLE.replace("@OWNER@", _owner_line(owner_name))
            .replace("@FREQ_NAME@", name)
            .replace("@FREQ@", PERSONAL_FREQUENCIES[name])
            .replace("@SOURCES@", _PERSONAL_SOURCES_FREE if free
                     else _PERSONAL_SOURCES_TOOLS if tools_available else _PERSONAL_SOURCES)
            .replace("@READONLY@", "" if free else _READONLY)
            .replace("@FREEDOM@", _freedom_section(actions=actions, mode=mode) if free else "")
            .replace("@TOOLS@", tools))
    if examples:
        text += (_PERSONAL_EXAMPLES.replace("@H_TRANSCRIPT@", H_TRANSCRIPT_PERSONAL)
                 .replace("@H_USER@", H_USER)
                 .replace("@H_REACTIONS@", H_REACTIONS))
    return text


def build_system(*, frequency=DEFAULT_FREQUENCY, tools_available: bool = True,
                 kb_map: str = "", owner_name: str = "", kb_exclude: Iterable[str] = (),
                 folders: Mapping[str, str] | None = None, glossary: str = "",
                 task_context: str = "", examples: bool = True, freedom: bool = False,
                 actions: bool = True, profile=DEFAULT_PROFILE, mode: str = "auto") -> str:
    """Системный промпт агента-участника.

    `frequency` — настройка «Как часто писать» («реже» / «обычно» / «чаще»);
    `tools_available` — у модели есть свои инструменты чтения: иначе в
    протоколе запросы к Meet `read` / `search` / `list`; `kb_map` — карта
    базы знаний (`kb_prep.kb_map`, без содержимого; пусто — карта в затравке
    или базы нет); `owner_name` — имя пользователя (по нему видно обращения к
    нему); `kb_exclude` — что закрыто настройками (у Claude Code запрет ещё и
    правилами CLI, у остальных — только эта строка); `folders` — подпись →
    путь папок, доступных инструментам (с инструментами); `profile` —
    профиль сессии: `work` — как в 0.3.6; `personal` — свой промпт, и карта,
    `kb_exclude`, глоссарий и контекст задачи в него не попадают (папки — те
    же); `freedom` (0.3.7, с инструментами) — раздел «Возможности и согласие
    пользователя» вместо «только чтение» (`meet.llm.consent`), один на оба
    профиля; `actions` — Claude Code (ворота Meet с карточками), иначе —
    Codex/OpenCode; `mode` (0.4, `assist.agent_mode`) — `auto` (действует
    сам, карточка — только рискованное; Codex/OpenCode — правят и выполняют
    сами, рискованное им нельзя) или `confirm` (карточка на каждое действие;
    Codex/OpenCode — только чтение файлов)."""
    if normalize_profile(profile) == PERSONAL:
        return _personal_system(frequency=frequency, tools_available=tools_available,
                               owner_name=owner_name, folders=folders, examples=examples,
                               freedom=freedom, actions=actions, mode=mode)
    name = normalize_frequency(frequency)
    owner_line = _owner_line(owner_name)
    map_where = ("Она — ниже." if (kb_map or "").strip()
                 else "Она приходит в первом сообщении сессии, если база знаний подключена.")
    free = bool(freedom and tools_available)
    if tools_available:
        dirs = [f"\n  - {safe_line(label)}: {safe_line(path)}"
                for label, path in (folders or {}).items() if str(path or "").strip()]
        if free:
            tools = _TOOLS_FREE.replace("@FOLDERS@", ("\n- Папки:" + "".join(dirs)) if dirs else "")
        else:
            tools = _TOOLS_ON.replace("@FOLDERS@", ("\n- Папки для чтения:" + "".join(dirs)) if dirs else "")
        protocol = ""
    else:
        tools = _TOOLS_OFF
        protocol = _PROTOCOL_OFF
    excluded = [safe_line(x) for x in kb_exclude if str(x or "").strip()]
    exclude = (f"- Закрыто настройками — не открывай и не ищи там: {', '.join(excluded)}.\n"
               if excluded else "")
    text = (_ROLE.replace("@OWNER@", owner_line)
            .replace("@FREQ_NAME@", name)
            .replace("@FREQ@", FREQUENCIES[name])
            .replace("@MAP_WHERE@", map_where)
            .replace("@READONLY@", "" if free else _READONLY)
            .replace("@TOOLS@", tools)
            .replace("@EXCLUDE@", exclude)
            .replace("@FREEDOM@", _freedom_section(actions=actions, mode=mode) if free else "")
            .replace("@PROTOCOL@", protocol))
    if examples:
        text += (_EXAMPLES.replace("@H_TRANSCRIPT@", H_TRANSCRIPT)
                 .replace("@H_REACTIONS@", H_REACTIONS))
    text += _section("Контекст задачи", task_context, TASK_MAX)
    text += _section("Глоссарий (термины команды)", glossary, GLOSSARY_MAX)
    kb = map_text(kb_map, SEED_MAP_MAX)
    if kb:
        text += f"\n# Карта базы знаний (названия, без содержимого)\n{data_block(kb)}\n"
    return text


_HEADING = re.compile(r"^(\s*)#+")
_INVISIBLE_OK = {"\u200d"}        # ZWJ — внутри эмодзи-последовательностей


def _visible(text: str, *, keep_newlines: bool = False) -> str:
    """Без управляющих и невидимых символов (Cc, Cf: нулевой ширины, bidi);
    перевод строки и табуляция — по `keep_newlines`."""
    keep = "\n\t" if keep_newlines else ""
    return "".join(ch for ch in text
                   if ch in keep or ch in _INVISIBLE_OK
                   or unicodedata.category(ch) not in ("Cc", "Cf"))


def map_text(kb_map, limit: int = SEED_MAP_MAX) -> str:
    """Карта для промпта: строки без разделителей ограды, невидимых символов и
    «#» в начале (название файла или встречи не начнёт свой раздел), целыми
    строками не длиннее `limit`."""
    lines = []
    for raw in str(kb_map or "").splitlines():
        line = _visible(unfence(raw)).rstrip()
        line = _HEADING.sub(lambda m: m.group(1) + "№", line)
        if line.strip():
            lines.append(line)
    return _fit_lines("\n".join(lines), limit, "… (карта обрезана)")


def data_block(text: str) -> str:
    """Текст в ограде данных `<<<ДАННЫЕ … >>>` (разделители внутри обезврежены)."""
    return "\n".join([DATA_OPEN, unfence(text).strip(), FENCE_CLOSE])


