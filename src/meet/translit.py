"""Латинские термины после GigaAM: «апи» → «API», «джира» → «Jira».

GigaAM подсказок не принимает и латиницу пишет кириллицей, как слышит. Список
терминов распознавания (hotwords.txt) при этом остаётся полезным: для каждого
термина с латиницей здесь строятся его вероятные кириллические записи, и они
заменяются обратно на термин — целыми словами, тем же механизмом, что правила
«Исправлять так же в будущих встречах» (meet.textfix.apply_rules: регистр
исправляемого, слова выровнены).

Осторожно, а не «как можно больше»: только термины, которые человек сам
добавил; запись короче трёх букв и обычные русские слова («кот» из «Kot»,
«порт» из «Port») не заменяются — ложная замена в чужой речи хуже пропуска.
Умная доработка поверх (модель по контексту) — отдельная задача.
"""

