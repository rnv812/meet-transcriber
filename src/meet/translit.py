def has_latin(text: str) -> bool:
    return bool(_LATIN.search(text or ""))


def _read(word: str, english: bool) -> str:
    w = word.lower()
    out, i = [], 0
    while i < len(w):
        for latin, cyr in _DIGRAPHS:
            if w.startswith(latin, i):
                out.append(cyr)
                i += len(latin)
                break
        else:
            ch = w[i]
            nxt = w[i + 1] if i + 1 < len(w) else ""
            if english and ch in _ENGLISH:
                out.append(_ENGLISH[ch])
            elif english and ch == "c" and nxt and nxt in _SOFT_C:
                out.append("с")
            elif english and ch == "y" and not nxt:
                out.append("и")
            else:
                out.append(_LETTERS.get(ch, ch))
            i += 1
    return "".join(out)


def _acronym(word: str) -> bool:
    return word.isupper() and 2 <= len(word) <= 5


def word_variants(word: str) -> list[str]:
    """Вероятные кириллические записи одного латинского слова (без повторов,
    порядок — от самого вероятного)."""
    if not has_latin(word):
        return [word.lower()]
    found = [_read(word, english=False), _read(word, english=True)]
    if _acronym(word):
        found.append(" ".join(_SPELLED[c] for c in word.lower()))
    return list(dict.fromkeys(v for v in found if v))


# Слишком много сочетаний у длинного термина — берём самые вероятные.
_MAX_VARIANTS = 8


def variants(term: str) -> list[str]:
    """Кириллические записи термина. Пусто — термин не латинский, с цифрами
    или его записи небезопасны (короткие, обычные русские слова)."""
    term = " ".join(str(term or "").split())
    if not has_latin(term) or any(c.isdigit() for c in term):
        return []
    words = _WORD.findall(term)
    if not words:
        return []
    out = []
    for combo in itertools.islice(itertools.product(*(word_variants(w) for w in words)),
                                  _MAX_VARIANTS):
        phrase = " ".join(combo)
        tokens = phrase.split()
        letters = sum(len(t) for t in tokens)
        if letters < 3:
            continue
        if len(tokens) == 1 and tokens[0].replace("ё", "е") in COMMON_RU:
            continue
        if all(t in COMMON_RU for t in tokens):
            continue
        out.append(phrase)
    return list(dict.fromkeys(out))


def rules_for(terms) -> list[dict]:
    """Правила «кириллическая запись → термин» ({"from", "to"}) для терминов
    распознавания с латиницей; формат — как у `asr.replacements`."""
    rules = []
    for term in terms or []:
        clean = " ".join(str(term or "").split())
        for phrase in variants(clean):
            rules.append({"from": phrase, "to": clean})
    return rules


def apply(segments: list, terms) -> int:
    """Вернуть латинские термины в распознанное GigaAM (сегменты — на месте).
    → сколько замен сделано."""
    from meet import textfix
    from meet.replacements import RULES_MAX

    rules = rules_for(terms)
    # apply_rules держит не больше RULES_MAX правил за раз — частями.
    return sum(textfix.apply_rules(segments, rules[i:i + RULES_MAX])
               for i in range(0, len(rules), RULES_MAX))
