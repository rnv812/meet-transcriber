import os as _os

# cuDNN — через прежний интерфейс PyTorch (0.5.1). Новый (v8) при первой свёртке
# в полной точности резервирует ~9 ГБ частной памяти: диаризация даже минуты
# звука доходила до 13,8 ГБ, и на занятой машине голоса падали с MemoryError
# или уводили систему в подкачку. Прежний даёт те же числа и ту же скорость
# (88 минут: те же спикеры, пик 5,1 ГБ). Здесь — до первого импорта torch в
# любом процессе движка; заданное руками значение не трогаем.
_os.environ.setdefault("TORCH_CUDNN_V8_API_DISABLED", "1")
