# Латинские буквы-двойники русских — внутри слов, где есть и русские буквы.
_HOMOGLYPHS = str.maketrans({"a": "а", "e": "е", "o": "о", "p": "р", "c": "с", "x": "х", "y": "у",
                             "k": "к", "m": "м", "t": "т", "h": "н", "b": "в", "i": "и", "u": "и",
                             "n": "п", "r": "г"})
_WORD = re.compile(r"[a-zа-я0-9]+")


def _fold(word: str) -> str:
    if re.search("[а-я]", word) and re.search("[a-z]", word):
        return word.translate(_HOMOGLYPHS)
    return word


def normalize(text: str) -> str:
    """Нижний регистр, «ё» → «е», дефисы и тире — пробелы, двойники в русских
    словах — русские, пробелы схлопнуты."""
    text = str(text or "").lower().replace("ё", "е")
    text = re.sub(r"[-‐‑‒–—]", " ", text)
    text = _WORD.sub(lambda m: _fold(m.group(0)), text)
    return " ".join(text.split())


def _pattern(stem: str) -> str:
    if stem.startswith("re:"):
        return stem[3:]
    words = [re.escape(w) for w in stem.replace("ё", "е").split()]
    tail = r"\s" if stem.endswith(" ") else ""
    return rf"(?<![{_L}])" + rf"[{_L}]*\s+".join(words) + tail


_RULES = (("medical", MEDICAL), ("protected", PROTECTED), ("worth", WORTH))
_PATTERNS = {name: re.compile("|".join(_pattern(s) for s in stems)) for name, stems in _RULES}


def reason(text: str) -> str | None:
    """Почему утверждение нельзя показывать: "medical", "protected", "worth"
    или None, если фильтр ничего не нашёл."""
    norm = _ALLOWED.sub(" ", normalize(text)) + " "
    if not norm.strip():
        return None
    for name, _stems in _RULES:
        if _PATTERNS[name].search(norm):
            return name
    return None


def unsafe(text: str) -> bool:
    return reason(text) is not None


