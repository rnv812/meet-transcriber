_L = "а-яa-z0-9"

# Короткие основы — только целым словом: «окружение», «гейт», «хамелеон»,
# «agenda» не ловим.
_WHOLE = {"окр", "гей", "хам", "ocd", "gay", "age"}

# Технические сочетания, которые не о человеке: вырезаются до проверки.
_ALLOWED = re.compile(
    rf"ленив[{_L}]*\s+(?:загрузк|инициализац|вычислен)[{_L}]*"
    rf"|примитивн[{_L}]*\s+(?:тип|операци|синхронизац)[{_L}]*"
    rf"|lazy\s+(?:loading|load|evaluation|init)[{_L}]*")


def _norm(text: str) -> str:
    return " ".join(str(text).lower().replace("ё", "е").split())


def _pattern(stem: str) -> str:
    stem = stem.replace("ё", "е")
    if stem in _WHOLE:
        return rf"(?<![{_L}]){re.escape(stem)}(?![{_L}])"
    words = [re.escape(w) for w in stem.split()]
    return rf"(?<![{_L}])" + rf"[{_L}]*\s+".join(words)


_RULES = (("medical", MEDICAL), ("protected", PROTECTED), ("worth", WORTH))
_PATTERNS = {name: re.compile("|".join(_pattern(s) for s in stems)) for name, stems in _RULES}


def reason(text: str) -> str | None:
    """Почему утверждение нельзя показывать: "medical", "protected", "worth"
    или None, если можно."""
    norm = _ALLOWED.sub(" ", _norm(text))
    if not norm.strip():
        return None
    for name, _stems in _RULES:
        if _PATTERNS[name].search(norm):
            return name
    return None


def unsafe(text: str) -> bool:
    return reason(text) is not None
