test("диапазоны: «с … по …», «-», «..», словами и через Новый год", () => {
  expect(p("с 1.09 по 15.09")).toEqual({ from: "2026-09-01", to: "2026-09-15", label: "1 сен – 15 сен" });
  expect(range("1.09-15.09")).toEqual(["2026-09-01", "2026-09-15"]);
  expect(range("1.09 - 15.09")).toEqual(["2026-09-01", "2026-09-15"]);
  expect(range("1.09–15.09")).toEqual(["2026-09-01", "2026-09-15"]);
  expect(range("1.09..15.09")).toEqual(["2026-09-01", "2026-09-15"]);
  expect(range("с 5 окт по 6 окт")).toEqual(["2026-10-05", "2026-10-06"]);
  expect(range("с 5 окт до 6 окт")).toEqual(["2026-10-05", "2026-10-06"]);
  expect(range("с 20.12 по 10.01")).toEqual(["2025-12-20", "2026-01-10"]);
  expect(p("с 20.12 по 10.01")?.label).toBe("20 дек 2025 – 10 янв");
  expect(range("с сентября по октябрь")).toEqual(["2026-09-01", "2026-10-31"]);
  expect(range("2026-09-01..2026-09-15")).toEqual(["2026-09-01", "2026-09-15"]);
  expect(range("2026-09-01-2026-09-15")).toEqual(["2026-09-01", "2026-09-15"]);
  // Год только у начала — конец после него.
  expect(range("1.09.2025-15.09")).toEqual(["2025-09-01", "2025-09-15"]);
  expect(range("с 1.12.2025 по 10.01")).toEqual(["2025-12-01", "2026-01-10"]);
  // Конец раньше начала, битый край — null.
  expect(p("15.09.2026-1.09.2026")).toBeNull();
  expect(p("с 31.02 по 5.03")).toBeNull();
  expect(p("1.09-")).toBeNull();
});

test("не даты", () => {
  for (const s of ["", "   ", "бюджет", "5", "окно", "ма", "марка", "1.2.3.4", "сегодня завтра", "с по"]) {
    expect(p(s)).toBeNull();
  }
});

test("числовая дата без префикса — сразу метка; год и слова — нет", () => {
  for (const s of ["05.10", "5.10.26", " 05.10.2026 ", "2026-10-05", "01.09-15.09", "01.09..15.09", "3.11.2025"]) {
    expect(isNumericDate(s, NOW)).toBe(true);
  }
  // Без двух цифр месяца и дня или без года — версии и доли: только подсказка.
  for (const s of ["2025", "вчера", "5 окт", "31.02", "05.10 бюджет", "5", "1.2.3", "1.5", "3.11", "2.10", "5.10",
    "1.09-15.09", "1.0"]) {
    expect(isNumericDate(s, NOW)).toBe(false);
  }
});

test("подписи диапазонов и месяцы по слову", () => {
  expect(rangeLabel("2026-10-05", "2026-10-05", NOW)).toBe("5 октября");
  expect(rangeLabel("2025-09-01", "2025-09-30", NOW)).toBe("Сентябрь 2025");
  expect(rangeLabel("2024-01-01", "2024-12-31", NOW)).toBe("2024");
  expect(rangeLabel("2026-10-01", "2026-10-03", NOW)).toBe("1 окт – 3 окт");
  expect(monthOf("мая")).toBe(4);
  expect(monthOf("июл")).toBe(6);
  expect(monthOf("ию")).toBe(-1);
  expect(monthOf("окт.")).toBe(9);
});

